class Finishing:
    def __init__(self, engine, *, lip_provider=None, sfx_provider=None, vfx_provider=None):
        self.engine, self.manager, self.path = engine, engine.manager, engine.path
        self.project_id = engine.project_id
        self.file = self.path / "finishing.json"
        self.lip_provider, self.sfx_provider, self.vfx_provider = lip_provider, sfx_provider, vfx_provider

    def load(self):
        return FinishingState.model_validate_json(read_text(self.file)) if self.file.exists() else FinishingState() if self.engine.assets.demo else FinishingState(plan=FinishingPlan(sound_provider="elevenlabs"))

    def save(self, state):
        atomic_write(self.file, state.model_dump_json(by_alias=True, indent=2))

    def scope(self, plan, sid):
        return {"lipSync": plan.lip_sync, "lipModel": plan.lip_model, "soundProvider": plan.sound_provider,
                "faces": [f.model_dump(mode="json") for f in plan.face_targets if f.scene_id == sid],
                "effects": [f.model_dump(mode="json") for f in plan.effects if f.scene_id == sid and f.enabled]}

    def signature(self, sid):
        state = self.load()
        if not state.plan.lip_sync and state.plan.sound_provider == "local" and not any(e.enabled and e.scene_id == sid for e in state.plan.effects):
            return None
        records = {}
        for key, record in state.records.items():
            if record.scene_id != sid or not record.asset:
                continue
            try:
                actual = file_hash(self.engine.assets.local_path(record.asset.file_path))
            except (OSError, ValueError):
                actual = None
            records[key] = {"inputHash": record.input_hash, "expectedFileHash": record.file_hash, "fileHash": actual,
                "assetId": record.asset.asset_id, "file": record.asset.file_path, "provider": record.asset.provider,
                "model": record.asset.model, "status": record.status}
        return {"plan": self.scope(state.plan, sid), "records": records}

    def resolved_sound(self, sid, sound):
        result = sound.model_dump(mode="json")
        state = self.load()
        if state.plan.sound_provider == "elevenlabs":
            for group in ("cues", "ambience"):
                for index, cue in enumerate(result[group]):
                    record = state.records.get(f"sfx:{sid}:{group}:{index}")
                    original = getattr(sound, group)[index]
                    if not cue["file"] and self.task_intact(record, ("sfx", group, index, original)):
                        cue["file"] = record.asset.file_path
                        cue["source"] = f"Generated by {record.asset.provider}/{record.asset.model}; asset {record.asset.asset_id}; see finishing.json and usage.json"
        return result

    def invalidate(self, scenes):
        state = self.engine.load()
        for sid in scenes:
            if sid in state.scenes:
                state.scenes[sid].status = "stale"
        state.status, state.approval = "stale", None
        self.engine._save(state)
        from .animation import load_animation, AnimationDirector
        direction = load_animation(self.path)
        if direction and direction.continuity_approval:
            direction.continuity_approval = None
            AnimationDirector(self.manager, self.project_id).save_state(direction)

    def configure(self, plan, *, expected):
        plan = FinishingPlan.model_validate(plan.model_dump() if isinstance(plan, FinishingPlan) else plan)
        production, board = self.engine._input()
        with project_lock(self.path):
            old = self.load()
            if old.plan.model_dump_json(by_alias=True) != expected:
                raise ValueError("Finishing settings changed; revert to load the latest version")
            by_id = {s.scene_id: s for s in board}
            for face in plan.face_targets:
                if face.scene_id not in by_id or face.character_id not in by_id[face.scene_id].character_ids:
                    raise ValueError("Face targets must use characters present in the selected scene")
                if face.subject is not None and not any(task.subject == face.subject and task.speaker == face.character_id
                        for task, *_ in self.voice_windows(by_id[face.scene_id], production)):
                    raise ValueError("A face target's subject must match that character's voice segment")
            for effect in plan.effects:
                if effect.scene_id not in by_id or effect.at + effect.duration > production.scenes[effect.scene_id].duration + .001:
                    raise ValueError("Effect layers must fit within an existing scene's recorded duration")
            atomic_write(self.path / "history" / "finishing" / f"{uuid4().hex}.json", old.model_dump_json(by_alias=True, indent=2))
            changed = [sid for sid in by_id if self.scope(old.plan, sid) != self.scope(plan, sid)]
            previous = {effect.effect_id: effect for effect in old.plan.effects}
            for effect in plan.effects:
                prior = previous.get(effect.effect_id)
                if prior and prior.model_dump(exclude={"at", "opacity", "enabled"}) != effect.model_dump(exclude={"at", "opacity", "enabled"}):
                    record = old.records.get(f"vfx:{effect.effect_id}")
                    if record:
                        record.modification_source, record.modification_prompt = None, ""
            old.plan = plan
            self.save(old)
            atomic_write(self.path / "finishing_plan.json", plan.model_dump_json(by_alias=True, indent=2))
            atomic_write(self.path / "finishing_plan.md", "# Lip-sync and effect layers\n\n"
                + f"Lip-sync: {plan.lip_sync}; model: {plan.lip_model}. Sound: {plan.sound_provider}.\n\n"
                + "\n".join(f"- {e.effect_id}: {e.scene_id}, {e.kind}, {e.at:g}–{e.at+e.duration:g}s, opacity {e.opacity:g}" for e in plan.effects))
            if changed:
                self.invalidate(changed)
            return old

    def preflight(self, scene, production, sound, *, credentials=True, only=None):
        plan = self.load().plan
        duration = production.scenes[scene.scene_id].duration
        if any(e.scene_id == scene.scene_id and e.enabled and e.at + e.duration > duration + .001 for e in plan.effects):
            raise ValueError("Update VFX timing to fit the current recorded scene duration")
        if plan.lip_sync and scene.dialogue and only in (None, "lip"):
            speakers = {line.character_id for line in scene.dialogue}
            if len(scene.character_ids) > 1:
                if any(self.face_for(plan, scene.scene_id, task) is None for task, *_ in self.voice_windows(scene, production)
                       if task.speaker != "narrator"):
                    raise ValueError("Set a face target for every dialogue speaker in this multi-character scene before generating lip-sync")
            if credentials and self.lip_provider is None and not os.environ.get("SYNC_API_KEY", "").strip():
                raise ValueError("Set SYNC_API_KEY in .env before generating lip-sync")
        cues = [*sound.cues, *sound.ambience]
        if plan.sound_provider == "elevenlabs" and any(not cue.file for cue in cues) and only in (None, "sfx") and (only == "sfx" or self.engine.load().options.sfx):
            if any(cue.duration > 30 and not cue.loop and not cue.file for cue in cues):
                raise ValueError("Generated sounds longer than 30 seconds must enable looping")
            if credentials and self.sfx_provider is None and not os.environ.get("ELEVENLABS_API_KEY", "").strip():
                raise ValueError("Set ELEVENLABS_API_KEY in .env before generating sound effects")
        if credentials and only in (None, "vfx") and self.vfx_provider is None and any(e.enabled and e.scene_id == scene.scene_id and e.kind == "openai" for e in plan.effects):
            if not os.environ.get("OPENAI_API_KEY", "").strip():
                raise ValueError("Set OPENAI_API_KEY in .env before generating AI VFX")

    def _intact(self, record):
        try:
            return bool(record and record.status == "succeeded" and record.asset
                        and file_hash(self.engine.assets.local_path(record.asset.file_path)) == record.file_hash)
        except (OSError, ValueError):
            return False

    def _generate(self, key, sid, payload, provider, model, callback, *, force=False):
        state = self.load()
        fingerprint = input_hash(payload)
        record = state.records.get(key)
        if not force and record and record.input_hash == fingerprint and self._intact(record):
            return self.engine.assets.local_path(record.asset.file_path)
        if record is None:
            record = FinishingRecord(key=key, scene_id=sid)
            state.records[key] = record
        if force or record.input_hash != fingerprint or record.job_status in ("FAILED", "REJECTED", "failed", "cancelled"):
            record.job_id, record.idempotency_key, record.work_dir = None, uuid4().hex, ""
            record.charge_recorded = False
            record.recorded_cost = Decimal(0)
            record.pricing_known = True
        if not record.idempotency_key:
            record.idempotency_key = uuid4().hex
        if not record.work_dir:
            record.work_dir = f"{'audio' if payload['provider'] == 'elevenlabs' else 'videos'}/finishing/{uuid4().hex}"
        record.input_hash, record.status, record.error = fingerprint, "running", None
        work = self.engine.assets.local_path(record.work_dir)
        work.mkdir(parents=True, exist_ok=True)
        def update(job_id, status, progress):
            record.job_id, record.job_status, record.progress = job_id, status, progress
            self.save(state)
        config = ProviderConfig(provider=payload["provider"], model=model, options={
            "job_id": record.job_id, "job_update": update, "idempotency_key": record.idempotency_key,
            "charge_recorded": record.charge_recorded,
            "poll_timeout": self.manager.settings.render_timeout_sec})
        self.save(state)
        # Only durable async jobs can be resumed automatically. Synchronous SFX
        # has no documented idempotency contract; failures remain explicit retries.
        attempts = self.manager.settings.llm_max_retries + 1 if provider is not None and payload["provider"] in ("sync", "openai") else 1
        for attempt in range(attempts):
            if self.engine.stop_requested():
                record.status = "pending" if record.attempts == 0 else "failed"
                record.error = "Stopped before the next finishing task; completed media was preserved"
                self.save(state)
                raise InterruptedError(record.error)
            record.attempts += 1
            self.save(state)
            outcome = "failed"
            if provider is not None:
                provider.last_usage = {}
            try:
                asset = callback(work, config)
                path = Path(asset.file_path).resolve()
                if not path.is_relative_to(self.path):
                    raise ValueError("Finishing provider returned media outside the project")
                if asset.type == "video":
                    self.engine.ffmpeg.validate(path)
                else:
                    self.engine.ffmpeg.run(["-i", path, "-map", "0:a:0", "-f", "null", "-"])
                asset.file_path, asset.source_scene_id = path.relative_to(self.path).as_posix(), sid
                if asset.generation_params.get("previewFile"):
                    preview = Path(asset.generation_params["previewFile"]).resolve()
                    if not preview.is_relative_to(self.path):
                        raise ValueError("Finishing preview is outside the project")
                    asset.generation_params["previewFile"] = preview.relative_to(self.path).as_posix()
                asset.generation_params.update(inputHash=fingerprint, sourceInputs=payload)
                usage = dict(getattr(provider, "last_usage", {}) or {}) if provider else {}
                asset.generation_params.update(requestIds=usage.get("request_ids", []), clientRequestIds=usage.get("client_request_ids", []))
                cost, _ = self._cost(payload["provider"], usage)
                asset.cost = record.recorded_cost + cost
                record.asset, record.file_hash = asset, file_hash(path)
                record.status, record.error = "succeeded", None
                record.revision += 1
                atomic_write(self.path / "history" / "finishing_assets" / f"{uuid4().hex}.json", record.model_dump_json(by_alias=True, indent=2))
                outcome = "succeeded"
                self.save(state)
                return path
            except Exception as exc:
                record.status, record.error = "failed", str(exc)
                self.save(state)
                config.options["job_id"] = record.job_id
                if (not isinstance(exc, TransientProviderError) or attempt == attempts - 1
                        or payload["provider"] == "openai" and not record.job_id):
                    raise
            finally:
                usage = dict(getattr(provider, "last_usage", {}) or {}) if provider else {}
                cost, known = self._cost(payload["provider"], usage)
                CostTracker(self.manager, self.project_id).record(UsageRecord(provider=payload["provider"], model=model,
                    step=f"finishing:{key}", scene_id=sid, outcome=outcome, retry_count=attempt,
                    video_seconds=usage.get("video_seconds", 0), audio_seconds=usage.get("audio_seconds", 0),
                    billing_units=usage.get("billing_units"), billing_unit=usage.get("billing_unit"), provider_job_id=record.job_id,
                    cost=cost, estimated_cost=cost, pricing_known=known, **request_fields(usage)))
                record.recorded_cost += cost
                record.pricing_known = record.pricing_known and known
                if usage.get("video_seconds", 0) > 0:
                    record.charge_recorded = config.options["charge_recorded"] = True
                self.save(state)
            time.sleep(min(2 ** attempt, 5))

    def _cost(self, provider, usage):
        if provider == "local":
            return Decimal(0), True
        field = "audio_seconds" if provider == "elevenlabs" else "video_seconds"
        rate = getattr(self.manager.settings, {"elevenlabs": "sfx_cost_per_second", "sync": "lip_sync_cost_per_second", "openai": "video_cost_per_second"}[provider])
        if field in usage and usage[field] == 0:
            return Decimal(0), True
        return (rate * Decimal(str(usage.get(field, 0))) if rate is not None else Decimal(0), rate is not None and field in usage)

    def sound(self, sid, group, index, cue, *, force=False):
        if self.sfx_provider is None:
            self.sfx_provider = ElevenLabsSFXProvider(timeout=self.manager.settings.llm_timeout_sec)
        provider = self.sfx_provider
        payload = sound_payload(cue, group)
        duration = payload["duration"]
        def generate(work, config):
            prompt = sound_prompt(self.engine.assets.creative, payload)
            config.options.update(output_path=str(work / "sound.mp3"), duration=duration, loop=cue.loop,
                                  prompt_influence=payload["promptInfluence"])
            return tracked_call(self.manager, self.project_id, f"finishing:sfx:{sid}:{group}:{index}", provider.generate, prompt, config)
        return self._generate(f"sfx:{sid}:{group}:{index}", sid, payload, provider, "eleven_text_to_sound_v2", generate, force=force)

    def task_intact(self, record, task):
        if task[0] == "sfx":
            _, group, _, cue = task
            if not record or record.input_hash != input_hash(sound_payload(cue, group)):
                return False
        return self._intact(record)

    def effect(self, effect, options, *, force=False):
        if effect.kind == "openai" and self.vfx_provider is None:
            self.vfx_provider = OpenAIVideoProvider(timeout=self.manager.settings.llm_timeout_sec)
        provider = self.vfx_provider if effect.kind == "openai" else None
        payload = {"provider": "local" if provider is None else "openai",
                   "effect": effect.model_dump(mode="json", exclude={"at", "opacity", "enabled"}),
                   "size": [options.width, options.height, options.fps], "model": options.video_model}
        record = self.load().records.get(f"vfx:{effect.effect_id}")
        if record and record.modification_source and provider is not None:
            payload.update(editSource=record.modification_source, modification=record.modification_prompt)
        def generate(work, config):
            if provider is None:
                from .vfx import generate_layer
                return generate_layer(effect, work / "layer.mov", options, self.engine.ffmpeg)
            seconds = 4 if effect.duration <= 4 else 8 if effect.duration <= 8 else 12
            config.options.update(output_path=str(work / "layer.mp4"), seconds=seconds, size=options.video_size)
            if payload.get("editSource"):
                config.options["edit_source"] = payload["editSource"]
            prompt = ("Generate only an isolated cinematic VFX element on a uniform vivid pure green (#00FF00) chroma-key background. "
                      "No characters, no scene, no camera movement, no text, no green in the effect itself. Keep the background perfectly flat for compositing. Effect: " + effect.prompt)
            if payload.get("modification"):
                prompt += " Modify the existing effect while retaining its chroma-key background: " + payload["modification"]
            return tracked_call(self.manager, self.project_id, f"finishing:vfx:{effect.effect_id}", provider.generate_clip, prompt, [], config)
        return self._generate(f"vfx:{effect.effect_id}", effect.scene_id, payload, provider,
                              "procedural-vfx-v1" if provider is None else options.video_model, generate, force=force)

    def modify_plan(self, instructions, *, expected):
        from .modification import modify_content
        with project_lock(self.path):
            state = self.load()
            if state.plan.model_dump_json(by_alias=True) != expected:
                raise ValueError("Finishing plan changed; reopen Modify with OpenAI")
            edited = modify_content(self.engine.assets.creative, state.plan, instructions, "finishing_plan")
        return self.configure(edited, expected=expected)

    def modify_effect(self, effect_id, instructions, *, expected):
        if not instructions.strip():
            raise ValueError("Describe the VFX modification")
        production, board = self.engine._input()
        with project_lock(self.path):
            state = self.load()
            effect = next((e for e in state.plan.effects if e.effect_id == effect_id and e.enabled and e.kind == "openai"), None)
            record = state.records.get(f"vfx:{effect_id}")
            render = self.engine._refresh(production, board)
            if not effect or not record or not record.asset or record.asset.asset_id != expected:
                raise ValueError("The effect changed; reopen Modify with OpenAI")
            if record.asset.model != render.options.video_model or not record.asset.generation_params.get("jobId"):
                raise ValueError("Use this effect's original OpenAI model and a generated video ID before modifying it")
            record.modification_source = record.asset.generation_params["jobId"]
            record.modification_prompt = instructions.strip()
            self.save(state)
            try:
                return self.effect(effect, render.options, force=True)
            finally:
                self.invalidate([effect.scene_id])

    def voice_windows(self, scene, production):
        cursor, windows = 0., []
        for task in self.engine.assets.tasks(production):
            if task.stage != "voices" or task.scene_id != scene.scene_id:
                continue
            record = production.records[task.key]
            audio = self.engine.assets.local_path(record.asset.file_path)
            duration = wav_duration(audio)
            windows.append((task, audio, cursor, duration))
            cursor += duration
        return windows

    def lip(self, scene, task, audio, start, duration, base, options, *, force=False):
        plan = self.load().plan
        face = self.face_for(plan, scene.scene_id, task)
        target = {"auto_detect": False, "frame_number": 0, "coordinates": [min(options.width-1, round(face.x*options.width)),
                  min(options.height-1, round(face.y*options.height))]} if face else None
        if self.lip_provider is None:
            self.lip_provider = SyncLipSyncProvider(timeout=self.manager.settings.llm_timeout_sec)
        provider = self.lip_provider
        payload = {"provider": "sync", "base": file_hash(base), "audio": file_hash(audio), "start": start,
                   "duration": duration, "face": target, "model": plan.lip_model, "size": [options.width, options.height, options.fps]}
        def generate(work, config):
            segment = work / "input.mp4"
            if not segment.exists():
                self.engine.ffmpeg.slice_visual(base, segment, start, duration, options)
            config.options.update(output_path=str(work / "synced.mp4"), face_target=target, duration=duration)
            asset = tracked_call(self.manager, self.project_id, f"finishing:lipsync:{task.subject}", provider.generate, segment, audio, config)
            actual = self.engine.ffmpeg.validate(Path(asset.file_path))
            if actual + 2/options.fps < duration:
                raise ValueError("Lip-sync output is shorter than the approved dialogue; regenerate instead of looping speech")
            return asset
        return self._generate(f"lipsync:{scene.scene_id}:{task.subject}", scene.scene_id, payload, provider, plan.lip_model, generate, force=force)

    def face_for(self, plan, sid, task):
        candidates = [face for face in plan.face_targets if face.scene_id == sid and face.character_id == task.speaker]
        return next((face for face in candidates if face.subject == task.subject),
                    next((face for face in candidates if face.subject is None), None))

    def apply_lip_sync(self, scene, production, base, options, work, *, force=False):
        if not self.load().plan.lip_sync or not scene.dialogue:
            return base
        paths, durations = [], []
        for index, (task, audio, start, duration) in enumerate(self.voice_windows(scene, production)):
            if self.engine.stop_requested():
                raise InterruptedError("Stopped after the current lip-sync task; completed segments were preserved")
            if task.speaker == "narrator":
                path = work / f"narration_{index}.mp4"
                self.engine.ffmpeg.slice_visual(base, path, start, duration, options)
            else:
                path = self.lip(scene, task, audio, start, duration, base, options, force=force)
            paths.append(path)
            durations.append(duration)
        destination = work / "lip_synced_scene.mp4"
        self.engine.ffmpeg.join_visuals(paths, durations, destination, options)
        return destination

    def tasks(self, production, board, render):
        plan = self.load().plan
        tasks = {}
        for scene in board:
            sid = scene.scene_id
            sound = render.music_plan.scenes[sid]
            if plan.sound_provider == "elevenlabs":
                for group in ("cues", "ambience"):
                    for index, cue in enumerate(getattr(sound, group)):
                        if not cue.file:
                            tasks[f"sfx:{sid}:{group}:{index}"] = (sid, f"{group}: {cue.name}", ("sfx", group, index, cue))
            for effect in plan.effects:
                if effect.scene_id == sid and effect.enabled:
                    tasks[f"vfx:{effect.effect_id}"] = (sid, effect.effect_id, ("vfx", effect))
            if plan.lip_sync:
                for task, audio, start, duration in self.voice_windows(scene, production):
                    if task.speaker != "narrator":
                        tasks[f"lipsync:{sid}:{task.subject}"] = (sid, f"{task.speaker}: {task.subject}", ("lip", scene, task, audio, start, duration))
        return tasks

    def generate_selected(self, keys, *, force=True):
        production, board = self.engine._input()
        with project_lock(self.path):
            render = self.engine._refresh(production, board)
            tasks = self.tasks(production, board, render)
            if not keys or not set(keys) <= tasks.keys():
                raise ValueError("Choose existing finishing items")
            for key in keys:
                if self.engine.stop_requested():
                    break
                sid, _, data = tasks[key]
                scene = next(s for s in board if s.scene_id == sid)
                self.preflight(scene, production, render.music_plan.scenes[sid], only=data[0])
                try:
                    if data[0] == "sfx":
                        self.sound(sid, *data[1:], force=force)
                    elif data[0] == "vfx":
                        self.effect(data[1], render.options, force=force)
                    else:
                        record = render.scenes[sid]
                        if not record.clip:
                            raise ValueError("Generate the base video with Generate scenes / shots on Animations before regenerating lip-sync segments")
                        self.lip(*data[1:], self.engine.assets.local_path(record.clip.file_path), render.options, force=force)
                except InterruptedError:
                    break
                finally:
                    self.invalidate([sid])
            return self.load()
